# ---------- 解析逐字时间 ----------
words = []  # (para, token, start_s, end_s)
for line in TXT.read_text(encoding='utf-8').splitlines():
    m = re.match(r'(\d+)\s*\|\s*([^|]+?)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|', line)
    if not m:
        continue
    words.append({'p': m.group(1), 't': m.group(2), 's': float(m.group(3)), 'e': float(m.group(4))})

# 每个段落一条字符流，token 可能是多字（1662 / AI），逐 token 拼接
paras = {}
for w in words:
    d = paras.setdefault(w['p'], {'text': '', 'map': []})  # map: char_index -> word
    for ch in w['t']:
        d['text'] += ch
        d['map'].append(w)

def find(para, phrase, cursor):
    """在段落字符流里从 cursor 起找 phrase，返回 (起帧, 止秒, 新cursor, 起秒)"""
    d = paras[para]
    i = d['text'].find(phrase, cursor)
    if i < 0:
        raise SystemExit(f'找不到: 段{para} «{phrase}» (cursor={cursor})')
    j = i + len(phrase) - 1
    return d['map'][i], d['map'][j], j + 1

