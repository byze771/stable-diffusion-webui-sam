out = {'fps': FPS, 'scenes': {}, 'subtitles': []}
all_subs = []
for scene, beats in B.items():
    s_out = {}
    cursors = {}
    for beat in beats:
        para = beat['para']
        cur = cursors.get(para, 0)
        subs_out = []
        first_f = None
        last_e = None
        for ph in beat['subs']:
            w0, w1, cur = find(para, ph, cur)
            s_f = round(w0['s'] * FPS)
            e_f = round(w1['e'] * FPS)
            if first_f is None:
                first_f = s_f
            last_e = e_f
            subs_out.append({'t': ph, 's': s_f, 'e': e_f})
        trig_out = {}
        # 每个 trig 从拍首独立找第一次出现，顺序无关
        beat_start_char = paras[para]['text'].find(beat['subs'][0], cursors.get(para, 0))
        for name, ph in beat.get('trig', {}).items():
            w0, w1, _ = find(para, ph, beat_start_char)
            trig_out[name] = round(w0['s'] * FPS)
        cursors[para] = cur
        s_out[beat['id']] = {'at': first_f, 'end': last_e, 'subs': subs_out, 'a': trig_out}
        all_subs.extend(subs_out)
    out['scenes'][scene] = {'beats': s_out}

